def build(topic=None):
    """按题材返回替换表。topic: 'badminton' / 'nasa' / 'inspiring' / None(全量)"""
    pool = list(GENERAL) + list(EXTRA)
    if topic in (None, "all"):
        pool += BADMINTON + NASA + INSPIRING
    else:
        pool += {"badminton": BADMINTON, "nasa": NASA, "inspiring": INSPIRING}[topic]
    # 去重保序
    seen, out = set(), []
    for a, b in pool:
        if a not in seen:
            seen.add(a)
            out.append((a, b))
    return out


